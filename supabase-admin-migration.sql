-- =========================
-- LIVE ADVERTISEMENTS
-- =========================
create table if not exists public.advertisements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  image_url text,
  button_text text default 'Order Now',
  button_link text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.advertisements enable row level security;

drop policy if exists "Public can view active advertisements" on public.advertisements;
create policy "Public can view active advertisements"
on public.advertisements for select
to anon, authenticated
using (active = true or public.is_admin());

drop policy if exists "Admins manage advertisements" on public.advertisements;
create policy "Admins manage advertisements"
on public.advertisements for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop trigger if exists advertisements_updated_at on public.advertisements;
create trigger advertisements_updated_at
before update on public.advertisements
for each row execute function public.set_updated_at();

