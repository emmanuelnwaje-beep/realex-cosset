-- BUSINESS LOCATIONS
-- =========================
create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'Branch',
  address text not null,
  city text,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.branches enable row level security;
drop policy if exists "Public can view active branches" on public.branches;
create policy "Public can view active branches" on public.branches for select to anon, authenticated using (active = true or public.is_admin());
drop policy if exists "Admins manage branches" on public.branches;
create policy "Admins manage branches" on public.branches for all to authenticated using (public.is_admin()) with check (public.is_admin());
